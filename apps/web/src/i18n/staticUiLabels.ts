export function useUiLabel() {
  const revision = useSyncExternalStore(subscribeLocale, getLocaleRevision, getLocaleRevision);
  const values = createUiLabels(revision);
  const labels: ReadonlyMap<string, string> = new Map(
    SOURCE_LABELS.map((source, index) => [source, values[index] ?? source]),
  );
  return (source: string): string => labels.get(source) ?? source;
}
